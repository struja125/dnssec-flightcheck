"""Measure real resolver software against the prediction, on loopback addresses.

One run starts the lab's authoritative servers and several instances of each resolver, queries
them on a compressed clock, and compares what they answer with the simulator:

* every instance starts being queried at a different moment, so at each change the caches of the
  population have different ages;
* background lookups of names that do not exist make the resolvers need the zone's keys at moments
  that do not depend on the measured names, as other clients' traffic does;
* a run only counts if the resolvers really validated: answers must carry the AD flag whenever
  the prediction says the zone is secure.
"""

