# resolver configurations


def _posix(path: Path) -> str:
    return path.resolve().as_posix()


def unbound_conf(lab: Path, instance: Instance, scale: float = 600) -> str:
    bogus_ttl = "val-bogus-ttl: 1" if scale > 1 else "# val-bogus-ttl keeps its default"
    return f"""# generated by flightcheck real-lab
server:
    interface: {instance.ip}
    port: 53
    access-control: 0.0.0.0/0 allow
    do-ip6: no
    directory: "{_posix(instance.directory)}"
    root-hints: "{_posix(lab / 'root.hints')}"
    trust-anchor-file: "{_posix(lab / 'root.ds')}"
    module-config: "validator iterator"
    do-not-query-localhost: no
    local-zone: "test." nodefault
    num-threads: 1
    outgoing-range: 128
    num-queries-per-thread: 64
    cache-min-ttl: 0
    {bogus_ttl}
    prefetch: no
    prefetch-key: no
    serve-expired: no
    ede: yes
    log-servfail: yes
    val-log-level: 2
    verbosity: 1
    use-syslog: no
    logfile: "{_posix(instance.directory / 'unbound.log')}"
    username: ""
    chroot: ""
    pidfile: ""
remote-control:
    control-enable: no
"""


def named_conf(lab: Path, instance: Instance, scale: float = 600) -> str:
    servfail_ttl = "servfail-ttl 0;" if scale > 1 else "// servfail-ttl keeps its default"
    ds_line = (lab / "root.ds").read_text(encoding="utf-8").split()
    tag, algorithm, digest_type, digest = ds_line[3], ds_line[4], ds_line[5], "".join(ds_line[6:])
    return f"""// generated by flightcheck real-lab
options {{
    directory "{_posix(instance.directory)}";
    pid-file none;
    session-keyfile none;
    listen-on port {instance.port} {{ {instance.ip}; }};
    listen-on-v6 {{ none; }};
    recursion yes;
    allow-query {{ any; }};
    allow-recursion {{ any; }};
    dnssec-validation yes;
    prefetch 0;
    stale-answer-enable no;
    stale-cache-enable no;
    {servfail_ttl}
    min-cache-ttl 0;
    min-ncache-ttl 0;
}};

controls {{ }};

trust-anchors {{
    . static-ds {tag} {algorithm} {digest_type} "{digest}";
}};

zone "." {{
    type hint;
    file "{_posix(lab / 'root.hints')}";
}};

logging {{
    channel log_file {{ file "{_posix(instance.directory / 'named.log')}"; severity info; print-time yes; }};
    category default {{ log_file; }};
    category dnssec {{ log_file; }};
}};
"""


def _instance(software: str, index: int, subnet: str, lab: Path) -> Instance:
    directory = lab / "resolvers" / f"{software}-{index}"
    if software == "bind":
        # BIND on Windows only listens on addresses it finds on an interface, so 127.0.0.1 with its own port.
        port = 5300 + int(subnet.split(".")[1]) * 20 + index
        return Instance(software, f"{software}-{index}", "127.0.0.1", directory, port=port)
    return Instance(software, f"{software}-{index}", f"{subnet}.{HOST_OFFSET[software] + index}", directory)


def _start_resolver(lab: Path, instance: Instance, scale: float) -> None:
    instance.directory.mkdir(parents=True, exist_ok=True)
    instance.log = (instance.directory / "stdout.log").open("wb")
    if instance.software == "unbound":
        conf = instance.directory / "unbound.conf"
        conf.write_text(unbound_conf(lab, instance, scale), encoding="utf-8")
        check = UNBOUND_EXE.with_name("unbound-checkconf.exe")
        command = [str(UNBOUND_EXE), "-d", "-c", str(conf)]
    else:
        conf = instance.directory / "named.conf"
        conf.write_text(named_conf(lab, instance, scale), encoding="utf-8")
        check = BIND_DIR / "named-checkconf.exe"
        command = [str(BIND_DIR / "named.exe"), "-g", "-c", str(conf)]
    verdict = subprocess.run([str(check), str(conf)], capture_output=True, text=True)
    if verdict.returncode != 0:
        raise RuntimeError(f"{instance.label}: invalid configuration:\n{verdict.stdout}{verdict.stderr}")
    instance.process = subprocess.Popen(command, stdout=instance.log, stderr=subprocess.STDOUT)


# ---------------------------------------------------------------------------
# one run


def run_real_lab(
    plan_path: str,
    out_dir: str,
    software: tuple[str, ...] = ("unbound", "bind"),
    instances: int = 3,
    scale: float = 600,
    interval: float = 0.25,
    subnet: str = "127.0.0",
    log=print,
) -> dict:
    lab = Path(out_dir).resolve()
    lab.mkdir(parents=True, exist_ok=True)
    addresses = {"root": f"{subnet}.10", "tld": f"{subnet}.11", "ns1": f"{subnet}.12", "ns2": f"{subnet}.13"}
    config = lab_init(plan_path, str(lab), scale=scale, start_delay=10, port=53, addresses=addresses)
    plan = load_plan(lab / "plan.yaml")
    config.start_wall = time.time() + 10
    config.save(lab)
    population = [_instance(name, i, subnet, lab) for name in software for i in range(instances)]

    server_log = (lab / "serve.log").open("wb")
    server = subprocess.Popen(
        [sys.executable, "-m", "flightcheck", "serve", "--lab", str(lab)], stdout=server_log, stderr=subprocess.STDOUT
    )
    samples: list[Sample] = []
    try:
        for instance in population:
            _start_resolver(lab, instance, scale)
        time.sleep(3)
        for instance in population:
            if instance.process.poll() is not None:
                raise RuntimeError(f"{instance.label} exited: see {instance.directory}")
        duration = config.end_wall - time.time()
        log(f"{plan.name}: {len(population)} resolvers, clock x{scale:g}, about {duration:.0f}s")
        _measure(plan, config, population, interval, samples)
    finally:
        for instance in population:
            if instance.process is not None:
                instance.process.terminate()
        server.terminate()
        for process in [i.process for i in population if i.process is not None] + [server]:
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
        for instance in population:
            if instance.log is not None:
                instance.log.close()
        server_log.close()
    return analyse(plan, config, software, instances, samples, interval)


def _measure(plan: Plan, config: LabConfig, population: list[Instance], interval: float, samples: list[Sample]) -> None:
    names = [f"{name}.{plan.zone}" for name in plan.data_names]
    first_step = min((s.at for s in plan.steps), default=0)
    warmup = (first_step - config.t_begin) / config.scale
    lock = threading.Lock()
    counts = {software: sum(1 for i in population if i.software == software) for software in {i.software for i in population}}
    positions: dict[str, int] = {}

    def probe_loop(instance: Instance, start_at: float) -> None:
        time.sleep(max(0, start_at - time.time()))
        while time.time() < config.end_wall:
            for name in names:
                sample = _ask(instance.label, instance.ip, instance.port, name, TIMEOUT, config)
                with lock:
                    samples.append(sample)
            time.sleep(interval)

    def background_loop(instance: Instance, start_at: float, seed: int) -> None:
        rng = random.Random(seed)
        time.sleep(max(0, start_at - time.time()))
        while time.time() < config.end_wall:
            _ask(instance.label, instance.ip, instance.port, f"bg-{rng.randrange(1 << 30)}.{plan.zone}", TIMEOUT, config)
            time.sleep(rng.expovariate(1 / (4 * interval)))

    threads = []
    for seed, instance in enumerate(population):
        position = positions.get(instance.software, 0)
        positions[instance.software] = position + 1
        start_at = config.start_wall + warmup * position / counts[instance.software]
        threads.append(threading.Thread(target=probe_loop, args=(instance, start_at), daemon=True))
        threads.append(threading.Thread(target=background_loop, args=(instance, start_at, seed), daemon=True))
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join(timeout=max(0, config.end_wall - time.time()) + TIMEOUT + 5)


