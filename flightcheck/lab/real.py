def analyse(plan: Plan, config: LabConfig, software, instances: int, samples: list[Sample], interval: float) -> dict:
    tolerance = config.scale * (interval + TIMEOUT)  # sampling and clock granularity, in plan seconds
    # A resolver keeps the security status of a cached answer, so an answer fetched while the zone
    # was still insecure can stay insecure for one more data TTL after the DS has reached it.
    qualifies = validated_answer_rule(plan, tolerance)
    results = {}
    for name in software:
        tuned = _tuned(plan, name, config.scale)
        on_clock = {model: simulate(tuned, model, memory_scale=config.scale) for model in MODELS}
        windows = {
            model: [(a, b + tolerance) for a, b in result.failure_windows()] for model, result in on_clock.items()
        }
        no_memory = {
            model: [(a, b + tolerance) for a, b in simulate(_tuned(plan, name, config.scale, memory=False), model).failure_windows()]
            for model in MODELS
        }
        mine = [s for s in samples if s.resolver.startswith(name + "-")]
        result = SoftwareResult(name, instances, lookups=len(mine), memory=lab_memory(name, config.scale))
        failures = []
        for sample in mine:
            if sample.status == SECURE:
                result.secure += 1
            elif sample.status == INSECURE:
                result.insecure += 1
                if not qualifies(sample):
                    result.unexpected_insecure += 1
            elif sample.status == BOGUS:
                result.servfail += 1
                failures.append(sample)
            elif sample.rcode == "TIMEOUT":
                result.timeouts += 1
                failures.append(sample)
            else:
                result.other += 1
            for code in sample.ede:
                result.ede[str(code)] = result.ede.get(str(code), 0) + 1
        if failures:
            result.first_failure = min(s.t for s in failures)
            result.last_failure = max(s.t for s in failures)
        max_gap = config.scale * max(interval * 4, TIMEOUT)
        result.comparison = {model: comparison_for(plan, name, config.scale, model, mine, tolerance, max_gap) for model in MODELS}
        holds = _holds(mine, config.scale * max(interval * 4, TIMEOUT))
        result.segments = _merge_holds(holds)
        measured = [(a, b) for a, b, status in result.segments if status == "bogus"]
        for model, prediction in on_clock.items():
            result.inside_without_memory[model] = sum(
                1 for s in failures if any(a <= s.t <= b for a, b in no_memory[model])
            )
            result.inside[model] = sum(1 for s in failures if any(a <= s.t <= b for a, b in windows[model]))
            ends = [end for _, end in windows[model]]
            outside = [s.t for s in failures if not any(a <= s.t <= b for a, b in windows[model])]
            result.overshoot[model] = (max(outside) - max(ends)) if outside and ends else None
            predicted = prediction.failure_windows()
            raw_end = max((b - tolerance for _, b in no_memory[model]), default=None)
            if failures and raw_end is not None and not math.isinf(raw_end):
                result.recovery_real[model] = (result.last_failure - raw_end) / config.scale
            # All three are plan seconds on this clock, and observed failures are counted inside the bound.
            result.predicted_seconds[model] = prediction.broken_time
            result.bound_seconds[model] = prediction.outage_time
            result.observed_seconds[model] = _overlap(measured, predicted)
        results[name] = result
    return {
        "default_timers": config.scale <= 1,
        "plan": plan.name,
        "coverage": plan.coverage,
        "provenance": provenance_lines(plan),
        "scale": config.scale,
        "interval": interval,
        "instances": instances,
        "results": results,
        "samples": samples,
    }


def _holds(samples: list[Sample], max_gap: float) -> list[tuple[float, float, str]]:
    series: dict[tuple, list[Sample]] = {}
    for sample in samples:
        series.setdefault((sample.resolver, sample.name), []).append(sample)
    holds = []
    for items in series.values():
        items.sort(key=lambda s: s.t)
        for current, following in zip(items, items[1:] + [None]):
            end = following.t if following is not None else current.t + max_gap / 4
            status = current.status if current.status in (SECURE, INSECURE) else BOGUS
            holds.append((current.t, min(end, current.t + max_gap), status))
    return holds


def report_text(run: dict) -> str:
    lines = [f"FlightCheck real resolvers - {run['plan']} (clock x{run['scale']:g})", *run.get("provenance", [])]
    for name, result in run["results"].items():
        lines.append(f"{SOFTWARE_NAMES[name]} ({result.instances} instances): {result.lookups} lookups")
        lines.append(
            f"  secure {result.secure}, insecure {result.insecure}, SERVFAIL {result.servfail}, "
            f"timeouts {result.timeouts}, other {result.other}"
        )
        lines.append(f"  really validating: {'yes' if result.validated else 'NO'}")
        if result.failures:
            lines.append(f"  first failure {format_offset(result.first_failure)}, last {format_offset(result.last_failure)}")
            lines.append(f"  EDE codes: {result.ede or '-'}")
        for model in MODELS:
            line = (
                f"  {model}: raw mismatch {format_duration(result.predicted_seconds[model])}, "
                f"upper bound with timers {format_duration(result.bound_seconds[model])}, "
                f"inside {result.inside[model]}/{result.failures} "
                f"(without timers {result.inside_without_memory[model]}/{result.failures})"
            )
            if result.predicted_seconds[model]:
                line += f", failing inside the bound for {format_duration(result.observed_seconds[model])}"
            if result.overshoot[model] is not None:
                line += f", latest failure {format_duration(result.overshoot[model])} after the window"
            if model in result.recovery_real:
                line += f", last failure {result.recovery_real[model]:.0f} real seconds after the raw mismatch ended"
            lines.append(line)
        lines.append("  compared with the fetch model:")
        lines += comparison_lines(result.comparison["fetch"], "    ")
    lines.append(f"Times are plan time relative to T+0; one real second is {run['scale']:g} plan seconds.")
    return "\n".join(lines) + "\n"


def run_status(run: dict) -> tuple[int, str]:
    """Exit code and reason: real-lab runs compare direct validators, so with the fetch model."""
    return run_outcome({name: result.comparison["fetch"] for name, result in run["results"].items()})


def report_html(run: dict, plan: Plan) -> str:
    conservative = simulate(plan, "conservative")
    fetch = simulate(plan, "fetch")
    measured = []
    summary = []
    extra = [fetch]
    for name, result in run["results"].items():
        title = SOFTWARE_NAMES[name]
        predicted = simulate(_tuned(plan, name, run["scale"]), "fetch", memory_scale=run["scale"])
        predicted.label = f"Predicted: {name}, this clock"
        extra.append(predicted)
        measured.append((f"{title} x{result.instances}", result.segments))
        comparison = result.comparison["fetch"]
        summary.append(
            (
                f"{title}: {comparison['classification']} (fetch model)",
                f"{result.inside['fetch']:,}/{result.failures:,}" if result.failures else "0 failures",
                f"{result.lookups:,} lookups, validating: {'yes' if result.validated else 'NO'}, "
                f"recovery: {comparison['recovery']}, EDE {result.ede or '-'}",
            )
        )
    summary.append(("clock", f"x{run['scale']:g}", f"one real second = {format_duration(run['scale'])} of plan time"))
    summary += provenance_row(plan)
    return render_html(conservative, fix=fix_plan(plan, "conservative"), extra=extra, measured=measured, lab_summary=summary)


def reanalyse(lab_dir: str) -> dict:
    """Run the analysis again on the samples of an earlier run."""
    lab = Path(lab_dir)
    data = json.loads((lab / "result.json").read_text(encoding="utf-8"))
    samples = [Sample(**sample) for sample in data["samples"]]
    plan = load_plan(lab / "plan.yaml")
    return analyse(plan, LabConfig.load(lab), tuple(data["results"]), data["instances"], samples, data["interval"])


def to_json(run: dict) -> str:
    data = dict(run)
    data["results"] = {name: {**asdict(result), "validated": result.validated} for name, result in run["results"].items()}
    data["samples"] = [asdict(sample) for sample in run["samples"]]
    return json.dumps(data, indent=1)
