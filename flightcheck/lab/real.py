ROOT = Path(__file__).resolve().parents[2]
UNBOUND_EXE = ROOT / "tools" / "unbound" / "ucrt64" / "bin" / "unbound.exe"
BIND_DIR = ROOT / "tools" / "bind"
SOFTWARE_NAMES = {"unbound": "Unbound 1.26.2", "bind": "BIND 9.16.50"}
HOST_OFFSET = {"unbound": 20, "bind": 40}
TIMEOUT = 2.0


@dataclass
class Instance:
    software: str
    label: str
    ip: str
    directory: Path
    port: int = 53
    process: subprocess.Popen | None = None
    log: object = None


@dataclass
class SoftwareResult:
    software: str
    instances: int
    lookups: int = 0
    secure: int = 0
    insecure: int = 0
    servfail: int = 0
    timeouts: int = 0
    other: int = 0
    unexpected_insecure: int = 0
    inside: dict = field(default_factory=dict)
    first_failure: float | None = None
    last_failure: float | None = None
    overshoot: dict = field(default_factory=dict)
    predicted_seconds: dict = field(default_factory=dict)
    observed_seconds: dict = field(default_factory=dict)
    recovery_real: dict = field(default_factory=dict)
    bound_seconds: dict = field(default_factory=dict)  # the windows with the resolver's timers: an upper bound
    comparison: dict = field(default_factory=dict)  # per model: see lab/comparison.py
    inside_without_memory: dict = field(default_factory=dict)
    memory: tuple = (0, 0)
    ede: dict = field(default_factory=dict)
    segments: list = field(default_factory=list)

    @property
    def failures(self) -> int:
        return self.servfail + self.timeouts

    @property
    def validated(self) -> bool:
        return self.unexpected_insecure == 0 and (self.secure > 0 or self.insecure > 0) and self.other == 0

    def consistent(self, model: str) -> bool:
        return self.inside.get(model, 0) == self.failures


